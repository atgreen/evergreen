//! Compiler variable keys keep uninterned identity without changing Lisp names.
use super::*;

const PREFIX: &str = "\0egcl-lexical:";
const SYMBOL: &str = "\0egcl-lexical:symbol:";
const NAME: &str = "\0egcl-lexical:name:";

/// Escape ordinary names that overlap the private encoding, including names
/// containing NUL. Global function/operator names never pass through this API.
pub(super) fn ordinary(name: &str) -> String {
    if name.starts_with(PREFIX) {
        format!("{NAME}{name}")
    } else {
        name.to_owned()
    }
}

pub(super) fn key(symbol: EgclVal) -> String {
    if let Some(index) = symbol
        .symbol_index()
        .filter(|&index| egcl_rt::symbols::is_uninterned(index))
    {
        format!("{SYMBOL}{index}")
    } else {
        ordinary(&sym_name(symbol))
    }
}

/// Only keys generated by this module reach compiled variable operations.
/// Serialized strings are ordinary names and must be escaped again on load;
/// serialized symbols reconstruct their key from their fresh loaded identity.
pub(super) fn symbol_index(key: &str) -> Option<u32> {
    let suffix = key.strip_prefix(SYMBOL)?;
    let index = suffix.parse::<u32>().ok()?;
    (egcl_rt::symbols::is_uninterned(index)
        && suffix.bytes().all(|byte| byte.is_ascii_digit())
        && (suffix.len() == 1 || !suffix.starts_with('0')))
    .then_some(index)
}

pub(super) fn name(key: &str) -> &str {
    key.strip_prefix(NAME).unwrap_or(key)
}

pub(super) fn symbol(key: &str) -> Option<EgclVal> {
    symbol_index(key).map(EgclVal::from_symbol_index)
}

pub(super) fn trace(key: &str, visit: &mut dyn FnMut(*mut EgclVal)) {
    if let Some(index) = symbol_index(key) {
        egcl_rt::symbols::trace_symbol_index(index, visit);
    }
}

pub(super) fn encoded(key: &str) -> bool {
    key.starts_with(PREFIX)
}

pub(super) fn index(key: &str) -> Option<u32> {
    symbol_index(key).or_else(|| egcl_rt::symbols::find_index(name(key)))
}

pub(super) fn resolve(key: &str) -> Option<EgclVal> {
    symbol(key).or_else(|| resolve_sym(name(key)))
}

    .text
    .p2align 2
    .globl egcl_context_swap
    .type egcl_context_swap,@function
egcl_context_swap:
    # ELFv2: 560-byte frame. Never save r13 (the carrier's TLS pointer).
    stdu 1,-560(1)
    mflr 0
    std 0,544(1)
    std 2,552(1)
    mfcr 0
    stw 0,528(1)
    mfspr 0,256
    stw 0,532(1)
    mffs 0
    stfd 0,536(1)
    mfvscr 0
    li 0,320
    stvx 0,1,0
    std 14,32(1)
    std 15,40(1)
    std 16,48(1)
    std 17,56(1)
    std 18,64(1)
    std 19,72(1)
    std 20,80(1)
    std 21,88(1)
    std 22,96(1)
    std 23,104(1)
    std 24,112(1)
    std 25,120(1)
    std 26,128(1)
    std 27,136(1)
    std 28,144(1)
    std 29,152(1)
    std 30,160(1)
    std 31,168(1)
    stfd 14,176(1)
    stfd 15,184(1)
    stfd 16,192(1)
    stfd 17,200(1)
    stfd 18,208(1)
    stfd 19,216(1)
    stfd 20,224(1)
    stfd 21,232(1)
    stfd 22,240(1)
    stfd 23,248(1)
    stfd 24,256(1)
    stfd 25,264(1)
    stfd 26,272(1)
    stfd 27,280(1)
    stfd 28,288(1)
    stfd 29,296(1)
    stfd 30,304(1)
    stfd 31,312(1)
    # v20-v31 are nonvolatile, including both 64-bit halves.
    li 0,336
    stvx 20,1,0
    li 0,352
    stvx 21,1,0
    li 0,368
    stvx 22,1,0
    li 0,384
    stvx 23,1,0
    li 0,400
    stvx 24,1,0
    li 0,416
    stvx 25,1,0
    li 0,432
    stvx 26,1,0
    li 0,448
    stvx 27,1,0
    li 0,464
    stvx 28,1,0
    li 0,480
    stvx 29,1,0
    li 0,496
    stvx 30,1,0
    li 0,512
    stvx 31,1,0
    std 1,0(3)
    mr 1,4
    li 0,320
    lvx 0,1,0
    mtvscr 0
    li 0,336
    lvx 20,1,0
    li 0,352
    lvx 21,1,0
    li 0,368
    lvx 22,1,0
    li 0,384
    lvx 23,1,0
    li 0,400
    lvx 24,1,0
    li 0,416
    lvx 25,1,0
    li 0,432
    lvx 26,1,0
    li 0,448
    lvx 27,1,0
    li 0,464
    lvx 28,1,0
    li 0,480
    lvx 29,1,0
    li 0,496
    lvx 30,1,0
    li 0,512
    lvx 31,1,0
    lfd 14,176(1)
    lfd 15,184(1)
    lfd 16,192(1)
    lfd 17,200(1)
    lfd 18,208(1)
    lfd 19,216(1)
    lfd 20,224(1)
    lfd 21,232(1)
    lfd 22,240(1)
    lfd 23,248(1)
    lfd 24,256(1)
    lfd 25,264(1)
    lfd 26,272(1)
    lfd 27,280(1)
    lfd 28,288(1)
    lfd 29,296(1)
    lfd 30,304(1)
    lfd 31,312(1)
    ld 14,32(1)
    ld 15,40(1)
    ld 16,48(1)
    ld 17,56(1)
    ld 18,64(1)
    ld 19,72(1)
    ld 20,80(1)
    ld 21,88(1)
    ld 22,96(1)
    ld 23,104(1)
    ld 24,112(1)
    ld 25,120(1)
    ld 26,128(1)
    ld 27,136(1)
    ld 28,144(1)
    ld 29,152(1)
    ld 30,160(1)
    ld 31,168(1)
    lfd 0,536(1)
    mtfsf 255,0
    lwz 0,532(1)
    mtspr 256,0
    lwz 0,528(1)
    mtcrf 255,0
    ld 2,552(1)
    # r12 must hold the global entry address on a fresh ELFv2 call so its
    # TOC prologue can establish r2. On resume, r2 is restored above.
    ld 12,544(1)
    mtlr 12
    addi 1,1,560
    blr
    .size egcl_context_swap,.-egcl_context_swap

    .globl egcl_context_init
    .type egcl_context_init,@function
egcl_context_init:
    # Inherit the creator's FP environment, not its carrier TLS.
    mffs 0
    stfd 0,536(3)
    mfvscr 0
    li 0,320
    stvx 0,3,0
    blr
    .size egcl_context_init,.-egcl_context_init
    .section .note.GNU-stack,"",@progbits
